#!/usr/bin/env python3
"""Generate self-contained channel Skill scripts from canonical aggregate sources."""

from __future__ import annotations

import argparse
import difflib
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Literal


REPO_ROOT = Path(__file__).resolve().parents[1]
CANONICAL_SCRIPTS = REPO_ROOT / "ai" / "collect-ai-trends" / "scripts"
GENERATED_NOTICE = "# Generated by tooling/generate_skills.py. Do not edit directly.\n"
CONFIG_START = "# BEGIN SKILL VARIANT CONFIG\n"
CONFIG_END = "# END SKILL VARIANT CONFIG\n"


@dataclass(frozen=True)
class SkillVariant:
    skill_name: str
    expected_source: Literal["reddit", "x", "github"] | None
    collector_module: str
    default_output_dir: str
    fixture_help: str
    preflight_help: str


VARIANTS = (
    SkillVariant(
        "collect-ai-trends",
        None,
        "collect_ai_trends",
        "ai-trend-output",
        "Read reddit.json, x.json, and github.json instead of calling CLIs",
        "Check opencli bridge and gh authentication, then exit",
    ),
    SkillVariant(
        "collect-github-ai-trends",
        "github",
        "collect_github_ai_trends",
        "github-ai-trend-output",
        "Read github.json instead of calling gh",
        "Check gh CLI and authentication, then exit",
    ),
    SkillVariant(
        "collect-reddit-ai-trends",
        "reddit",
        "collect_reddit_ai_trends",
        "reddit-ai-trend-output",
        "Read reddit.json instead of calling opencli",
        "Check the opencli bridge, then exit",
    ),
    SkillVariant(
        "collect-x-ai-trends",
        "x",
        "collect_x_ai_trends",
        "x-ai-trend-output",
        "Read x.json instead of calling opencli",
        "Check the opencli bridge, then exit",
    ),
)


def generated_header(content: str) -> str:
    lines = content.splitlines(keepends=True)
    if lines and lines[0].startswith("#!"):
        return lines[0] + GENERATED_NOTICE + "".join(lines[1:])
    return GENERATED_NOTICE + content


def replace_variant_config(content: str, variant: SkillVariant) -> str:
    start = content.index(CONFIG_START)
    end = content.index(CONFIG_END, start) + len(CONFIG_END)
    sources = (
        "(\"reddit\", \"x\", \"github\")"
        if variant.expected_source is None
        else f"(\"{variant.expected_source}\",)"
    )
    expected = "None" if variant.expected_source is None else f'"{variant.expected_source}"'
    block = (
        CONFIG_START
        + 'SCHEMA_VERSION = "1.0"\n'
        + 'ALL_SOURCE_NAMES = ("reddit", "x", "github")\n'
        + f"SOURCE_NAMES = {sources}\n"
        + f"EXPECTED_SOURCE: str | None = {expected}\n"
        + f"DEFAULT_OUTPUT_DIR = {variant.default_output_dir!r}\n"
        + f"FIXTURE_HELP = {variant.fixture_help!r}\n"
        + f"PREFLIGHT_HELP = {variant.preflight_help!r}\n"
        + CONFIG_END
    )
    return content[:start] + block + content[end:]


def render_scripts(variant: SkillVariant) -> dict[str, str]:
    collector = (CANONICAL_SCRIPTS / "collect_ai_trends.py").read_text(encoding="utf-8")
    finalizer = (CANONICAL_SCRIPTS / "finalize_ai_trends.py").read_text(encoding="utf-8")
    validator = (CANONICAL_SCRIPTS / "validate_x_drafts.py").read_text(encoding="utf-8")
    collector = replace_variant_config(collector, variant)
    finalizer = finalizer.replace("from collect_ai_trends import (", f"from {variant.collector_module} import (")
    outputs = {
        f"{variant.collector_module}.py": collector,
        "finalize_ai_trends.py": finalizer,
        "validate_x_drafts.py": validator,
    }
    if variant.expected_source is not None:
        outputs = {name: generated_header(content) for name, content in outputs.items()}
    return outputs


def destination_scripts(output_root: Path, variant: SkillVariant) -> Path:
    return output_root / "ai" / variant.skill_name / "scripts"


def check_generated() -> int:
    drifted: list[str] = []
    for variant in VARIANTS[1:]:
        scripts_dir = destination_scripts(REPO_ROOT, variant)
        for filename, expected in render_scripts(variant).items():
            path = scripts_dir / filename
            actual = path.read_text(encoding="utf-8") if path.exists() else ""
            if actual == expected:
                continue
            drifted.append(str(path.relative_to(REPO_ROOT)))
            diff = difflib.unified_diff(
                actual.splitlines(),
                expected.splitlines(),
                fromfile=str(path),
                tofile=f"generated:{path}",
                n=2,
            )
            print("\n".join(list(diff)[:80]))
    if drifted:
        print("generated files are stale: " + ", ".join(drifted), file=sys.stderr)
        return 1
    print("generated Skill scripts are up to date")
    return 0


def write_generated(output_root: Path) -> int:
    for variant in VARIANTS:
        scripts_dir = destination_scripts(output_root, variant)
        scripts_dir.mkdir(parents=True, exist_ok=True)
        for filename, content in render_scripts(variant).items():
            path = scripts_dir / filename
            path.write_text(content, encoding="utf-8")
            path.chmod(0o755)
        if output_root != REPO_ROOT:
            source_skill = REPO_ROOT / "ai" / variant.skill_name
            for relative in ("SKILL.md", "agents", "references"):
                source = source_skill / relative
                destination = output_root / "ai" / variant.skill_name / relative
                if source.is_dir():
                    shutil.copytree(source, destination, dirs_exist_ok=True)
                elif source.is_file():
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(source, destination)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when committed generated scripts are stale")
    parser.add_argument("--output-root", type=Path, default=REPO_ROOT, help="Repository-shaped output directory")
    args = parser.parse_args()
    if args.check:
        return check_generated()
    return write_generated(args.output_root.resolve())


if __name__ == "__main__":
    raise SystemExit(main())
